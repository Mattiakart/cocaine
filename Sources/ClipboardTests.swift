        var lim = base; lim.maxItems = 3; lim.maxAgeHours = 0
        core = ClipHistoryCore()
        for i in 0..<5 { core.add(.text("n\(i)", date: t0 + Double(i))) }
        core.items[core.items.firstIndex { $0.text == "n0" }!].pinned = true
        let pruned = core.prune(now: t0 + 10, settings: lim)
        check("count limit drops the oldest, favorites survive and don't count", core.items.map(\.text) == ["n4", "n3", "n2", "n0"] && pruned.map(\.text) == ["n1"])
        var age = base; age.maxAgeHours = 24
        core = ClipHistoryCore()
        core.add(.text("old", date: t0 - 3 * 86400)); core.add(.text("oldfav", date: t0 - 3 * 86400)); core.add(.text("new", date: t0))
        core.items[core.items.firstIndex { $0.text == "oldfav" }!].pinned = true
        core.prune(now: t0, settings: age)
        check("age limit removes old items, not favorites", core.items.map(\.text).sorted() == ["new", "oldfav"])
        var space = base; space.maxTotalMB = 1; space.maxAgeHours = 0
        core = ClipHistoryCore()
        for i in 0..<4 { core.add(.image(png: Data(repeating: UInt8(i), count: 400_000), width: 10, height: 10, date: t0 + Double(i))) }
        core.prune(now: t0, settings: space)
        check("total size limit drops the oldest until it fits", core.items.count == 2 && core.items.reduce(0) { $0 + $1.bytes } <= 1_000_000)
        var noAge = base; noAge.maxAgeHours = 0
        core = ClipHistoryCore(); core.add(.text("ancient", date: t0 - 400 * 86400)); core.prune(now: t0, settings: noAge)
        check("'no limit' age keeps everything", core.items.count == 1)

        core = ClipHistoryCore()
        core.add(.text("Café au lait recipe")); core.add(.files(["/Users/x/Documents/Report Q3.pdf"]))
        core.add(.image(png: Data([1]), width: 1920, height: 1080)); core.add(.text("brew upgrade --cask cocaine"))
        core.items[core.items.firstIndex { $0.text.hasPrefix("brew") }!].pinned = true
        check("search: any case and accents", core.filtered("CAFE", favoritesOnly: false).count == 1)
        check("search: every word must match", core.filtered("cafe recipe", favoritesOnly: false).count == 1 && core.filtered("cafe brew", favoritesOnly: false).isEmpty)
        check("search: file names and folders", core.filtered("report", favoritesOnly: false).first?.kind == .files
              && core.filtered("documents", favoritesOnly: false).count == 1)
        check("search: image size", core.filtered("1920", favoritesOnly: false).first?.kind == .image)
        check("search: what describe adds (source app)", core.filtered("terminal", favoritesOnly: false, describe: { $0.text.hasPrefix("brew") ? "Terminal" : "" }).count == 1)
        check("favorites only", core.filtered("", favoritesOnly: true).map(\.text) == ["brew upgrade --cask cocaine"])
        check("empty search shows everything", core.filtered("  ", favoritesOnly: false).count == 4)

        // MARK: encryption
        let k1 = SymmetricKey(size: .bits256), k2 = SymmetricKey(size: .bits256)
        let secret = Data("the clipboard text".utf8)
        let sealed = try? ClipCrypto.seal(secret, key: k1, context: "index")
        check("encryption round trip", sealed.flatMap { try? ClipCrypto.open($0, key: k1, context: "index") } == secret)
        check("the sealed data doesn't contain the text", sealed.map { $0.range(of: secret) == nil } ?? false)
        check("a wrong key is rejected", sealed.map { (try? ClipCrypto.open($0, key: k2, context: "index")) == nil } ?? false)
        check("a changed byte is rejected", sealed.map { s -> Bool in var d = s; d[d.count - 1] ^= 1; return (try? ClipCrypto.open(d, key: k1, context: "index")) == nil } ?? false)
        check("data moved to another place (context) is rejected", sealed.map { (try? ClipCrypto.open($0, key: k1, context: "image:x")) == nil } ?? false)
        check("not our format is rejected", (try? ClipCrypto.open(Data("hello".utf8), key: k1, context: "index")) == nil)

        // MARK: the store
        func perms(_ u: URL) -> Int { ((try? fm.attributesOfItem(atPath: u.path))?[.posixPermissions] as? NSNumber)?.intValue ?? -1 }
        let keys = MemoryKeyStore()
        let dir = root.appendingPathComponent("store")
        let store = ClipStore(dir: dir, keys: keys)
        check("store: unlocking makes and keeps a 256-bit key", (try? store.unlock()) != nil && keys.key?.count == 32)
        let png = samplePNG()
        let img = ClipItem.image(png: png, width: 4, height: 3, date: t0)
        var fav = ClipItem.text("favorite text", date: t0); fav.pinned = true
        let list = [ClipItem.text("hello secret world", date: t0, source: "com.apple.TextEdit"), fav, ClipItem.files(["/tmp/x.txt"], date: t0), img]
        try? store.writeImage(img.id, png)
        let saved = (try? store.saveIndex(list)) != nil
        let back = ClipStore(dir: dir, keys: keys)
        try? back.unlock()
        let loaded = back.load()
        check("store: round trip of text, files, image, star, source", saved && loaded.problem == .none && loaded.items.count == 4
              && loaded.items[0].text == "hello secret world" && loaded.items[0].source == "com.apple.TextEdit" && loaded.items[1].pinned
              && loaded.items[2].paths == ["/tmp/x.txt"] && back.readImage(img.id) == png && loaded.items[3].payload == nil)
        check("store: folder 0700, files 0600", perms(dir) == 0o700 && perms(store.index) == 0o600 && perms(store.blob(img.id)) == 0o600)
        let indexBytes = (try? Data(contentsOf: store.index)) ?? Data()
        check("store: nothing readable on disk", indexBytes.range(of: Data("hello secret world".utf8)) == nil && indexBytes.range(of: Data("/tmp/x.txt".utf8)) == nil
              && ((try? Data(contentsOf: store.blob(img.id)))?.range(of: png.prefix(16)) == nil))
        check("store: no temp files left behind", !((try? fm.contentsOfDirectory(atPath: dir.path)) ?? []).contains { $0.hasPrefix(".tmp-") })
        let wrongKey = ClipStore(dir: dir, keys: MemoryKeyStore())
        try? wrongKey.unlock()
        let wrongLoad = wrongKey.load()
        let asides = ((try? fm.contentsOfDirectory(atPath: dir.path)) ?? []).filter { $0.hasPrefix("unreadable-") }
        let aside = asides.first.map { dir.appendingPathComponent($0) }
        check("store: another key can't read it (set aside with its images, nothing deleted; starts empty)", wrongLoad.items.isEmpty
              && wrongLoad.problem == .unreadableIndex && asides.count == 1 && !fm.fileExists(atPath: store.blob(img.id).path)
              && aside.map { fm.fileExists(atPath: $0.appendingPathComponent(store.index.lastPathComponent).path)
                             && fm.fileExists(atPath: $0.appendingPathComponent(store.blob(img.id).lastPathComponent).path) } == true)
        do {   // there, but unreadable (permissions, I/O): not "no history" (which would delete the images)
