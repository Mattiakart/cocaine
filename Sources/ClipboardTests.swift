        }
        let base = ClipSettings()

        // MARK: what is never kept
        func kept(_ s: ClipSnapshot, _ settings: ClipSettings = ClipSettings()) -> Bool {
            if case .keep = ClipRules.decide(s, settings: settings) { return true } else { return false }
        }
        func skip(_ s: ClipSnapshot, _ settings: ClipSettings = ClipSettings()) -> ClipRules.Skip? {
            if case .skip(let r) = ClipRules.decide(s, settings: settings) { return r } else { return nil }
        }
        check("plain text is kept", kept(text("hello world")))
        check("whitespace only is not kept", skip(text("  \n ")) == .empty)
        check("concealed (password manager) content is skipped", skip(text("hunter2", types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"])) == .concealed)
        check("transient and auto-generated content is skipped",
              skip(text("x", types: ["org.nspasteboard.TransientType"])) == .concealed && skip(text("x", types: ["org.nspasteboard.AutoGeneratedType"])) == .concealed)
        check("1Password's own marker is skipped", skip(text("x", types: ["com.agilebits.onepassword"])) == .concealed)
        check("password managers are excluded by source", skip(text("x", source: "com.1password.1password")) == .excludedApp
              && skip(text("x", source: "com.bitwarden.desktop")) == .excludedApp && skip(text("x", source: "com.apple.keychainaccess")) == .excludedApp
              && skip(text("x", source: "com.apple.Passwords")) == .excludedApp)
        check("ordinary apps are not excluded", kept(text("x y", source: "com.apple.TextEdit")))
        var ex = base; ex.excludedApps = ["com.example.Secret"]
        check("the user's excluded apps are skipped (any case)", skip(text("x y", source: "com.example.secret"), ex) == .excludedApp)
        check("card number (Luhn) is skipped", skip(text("4111 1111 1111 1111")) == .secret && skip(text("4111-1111-1111-1111")) == .secret)
        check("digits that fail the check digit are kept", kept(text("4111 1111 1111 1112")))
        check("phone numbers and short numbers are kept", kept(text("+39 333 1234567")) && kept(text("12345")))
        check("API tokens are skipped", ClipRules.looksLikeSecret("ghp_aBcD1234eFgH5678iJkL9012mNoP3456qRsT")
              && ClipRules.looksLikeSecret("AKIAIOSFODNN7EXAMPLE") && ClipRules.looksLikeSecret("sk-proj-Ab12Cd34Ef56Gh78Ij90"))
        check("a JWT is skipped", ClipRules.looksLikeSecret("eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.dozjgNryP4J3jVmNHl0w5N_XgL0n3I9PlFUP0THsR8U"))
        check("a private key block is skipped", ClipRules.looksLikeSecret("-----BEGIN OPENSSH PRIVATE KEY-----\nabc\n-----END OPENSSH PRIVATE KEY-----"))
        check("a long random string is skipped", ClipRules.looksLikeSecret("q8Zr2LkT9vXw4NbP7sHd3FgJ6mYc"))
        check("URLs, paths, words, e-mails, hashes and UUIDs are kept",
              !ClipRules.looksLikeSecret("https://github.com/Mattiakart/cocaine/releases/tag/v1.7.3")
              && !ClipRules.looksLikeSecret("/Users/someone/Library/Application Support/Cocaine")
              && !ClipRules.looksLikeSecret("Supercalifragilisticexpialidocious")
              && !ClipRules.looksLikeSecret("mattia.example1234567890@example.com")
              && !ClipRules.looksLikeSecret("e23874c1f0a9b8c7d6e5f4a3b2c1d0e9f8a7b6c5")
              && !ClipRules.looksLikeSecret("123E4567-E89B-12D3-A456-426614174000")
              && !ClipRules.looksLikeSecret("brew upgrade --cask cocaine"))
        var noSecrets = base; noSecrets.skipSecrets = false
        check("with the secret filter off, a card number is kept", kept(text("4111 1111 1111 1111"), noSecrets))
        var pat = base; pat.patterns = ["^IBAN", "\\bconfidential\\b", "(unclosed"]
        check("the user's pattern skips matching text", skip(text("IBAN IT60X0542811101000000123456"), pat) == .pattern
              && skip(text("this is Confidential stuff"), pat) == .pattern)
        check("an invalid pattern is ignored, not a crash, and refused when typed", kept(text("hello there"), pat) && !ClipRules.validPattern("(unclosed")
              && ClipRules.validPattern("^IBAN") && !ClipRules.validPattern(""))
        var tiny = base; tiny.maxItemMB = 1
        check("text over the item size is skipped", skip(text(String(repeating: "a", count: 1_000_001)), tiny) == .tooBig)
        check("an image over the item size is skipped", skip(ClipSnapshot(types: ["public.png"], image: Data(count: 1_000_001), width: 1, height: 1), tiny) == .tooBig
              && skip(ClipSnapshot(types: ["public.tiff"], imageTooBig: true), tiny) == .tooBig)
        check("files win over their names as text", {
            guard case .keep(let i) = ClipRules.decide(ClipSnapshot(types: ["public.file-url", "public.utf8-plain-text"], text: "a.txt",
                                                                    files: [URL(fileURLWithPath: "/tmp/a.txt")]), settings: base) else { return false }
            return i.kind == .files && i.paths == ["/tmp/a.txt"]
        }())
        check("our own writes are not captured", skip(ClipSnapshot(types: [ClipRules.ownType], ours: true, text: "x")) == .own)

        // MARK: the list
        let t0 = Date(timeIntervalSince1970: 1_790_000_000)
        var core = ClipHistoryCore()
        let a = ClipItem.text("alpha", date: t0)
        core.add(a); core.add(.text("beta", date: t0 + 1)); core.add(.text("alpha", date: t0 + 2))
        check("dedupe: the same text again moves to the top, no duplicate", core.items.map(\.text) == ["alpha", "beta"] && core.items[0].id == a.id
