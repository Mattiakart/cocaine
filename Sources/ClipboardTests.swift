        check("store: wipe removes the folder and the key", (try? s2.wipe()) != nil && !fm.fileExists(atPath: dir2.path) && keys2.key == nil && !s2.unlocked)

        // MARK: the history, with a fake clipboard
        func history(_ name: String, keys: MemoryKeyStore = MemoryKeyStore(), board: FakePasteboard = FakePasteboard(), d: UserDefaults? = nil) -> ClipboardHistory {
            let h = ClipboardHistory(defaults: d ?? defaults(), dir: root.appendingPathComponent(name), keys: keys, board: board)
            h.frontApp = { "com.apple.TextEdit" }
            return h
        }
        let fb = FakePasteboard()
        let h = history("h1", board: fb)
        check("history: memory only by default", !h.settings.persist && !h.saving)
        fb.put(text("first")); h.captureNow()
        fb.put(text("second")); h.captureNow()
        fb.put(text("first")); h.captureNow()
        check("history: captures and dedupes (moved to top)", h.items.map(\.text) == ["first", "second"])
        check("history: the source app is recorded", h.items[0].source == "com.apple.TextEdit")
        check("history: memory only writes nothing to disk", !fm.fileExists(atPath: root.appendingPathComponent("h1").path))
        let reads = fb.dataReads
