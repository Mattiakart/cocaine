        fb.put(text("from the vault")); h.captureNow()
        check("history: the frontmost excluded app's copy isn't kept or read", h.items.count == 2 && fb.dataReads == reads)
        h.frontApp = { "com.apple.TextEdit" }
        check("history: copying an item again isn't captured as new, and moves it up", h.copy(h.items[1]) && h.items.map(\.text) == ["second", "first"]
              && fb.written.last?.text == "second")
        h.frontApp = { "com.example.other" }
        h.captureNow()
        check("history: …even when the clipboard is read after it", h.items.count == 2 && h.items[0].source == "com.apple.TextEdit")
        h.frontApp = { "com.apple.TextEdit" }
        h.paused = true
        fb.put(text("while paused")); h.captureNow()
        h.paused = false
        h.captureNow()
        check("history: nothing copied while paused is kept, even after resuming", !h.items.contains { $0.text == "while paused" })
        fb.put(text("late")); fb.emptyReadsLeft = 1; h.captureNow()
        check("history: content that arrives late is read again", h.items.first?.text == "late")
        h.togglePin(h.items.first { $0.text == "first" }!.id)
        h.clearHistory()
        check("history: clear keeps the favorites", h.items.map(\.text) == ["first"])
        h.remove(h.items[0].id)
        check("history: delete one item", h.items.isEmpty)
        fb.put(text("from app x", source: "com.example.x")); h.captureNow()
        fb.put(text("from textedit")); h.captureNow()
        var exX = h.settings; exX.excludedApps.append("com.example.x"); h.update(exX)
        check("history: excluding an app removes what came from it", h.items.map(\.text) == ["from textedit"])
        h.query = "TEXTEDIT"
        check("history: search sees the text", h.visible.count == 1)
        h.query = "nothing like this"
        check("history: search filters", h.visible.isEmpty)
        h.query = ""

        // file references
        let realFile = root.appendingPathComponent("Real Report.pdf"), goneFile = root.appendingPathComponent("Gone.pdf")
        try? Data("pdf".utf8).write(to: realFile); try? Data("pdf".utf8).write(to: goneFile)
        fb.put(ClipSnapshot(types: ["public.file-url"], files: [realFile])); h.captureNow()
        fb.put(ClipSnapshot(types: ["public.file-url"], files: [goneFile])); h.captureNow()
        try? fm.removeItem(at: goneFile)
