        later.start(); later.stop()
        check("persistence: expired items are dropped at load, favorites stay", later.items.map(\.text) == ["before saving"])
        later.setPersist(false, wipe: false)
        check("persistence: off and kept, the files stay (encrypted), the key too", !later.saving && fm.fileExists(atPath: pdir.path) && pk.key != nil)
        later.setPersist(true)
        later.setPersist(false, wipe: true)
        check("persistence: off and wiped, files and key are gone", !fm.fileExists(atPath: pdir.path) && pk.key == nil && !later.settings.persist)

        let fk = MemoryKeyStore(); fk.failing = true
        let fh = history("f", keys: fk)
        fh.add(.text("kept in memory"))
        fh.setPersist(true)
        check("persistence: no Keychain, no saving (memory only, said plainly)", !fh.saving && !fh.settings.persist && fh.problem != nil
              && !fm.fileExists(atPath: root.appendingPathComponent("f").path) && fh.items.count == 1)
        do {   // a Keychain that says no at launch (locked, a prompt refused) doesn't turn the choice off for good
            let lk = MemoryKeyStore(), ld = defaults()
            let lh = history("l", keys: lk, d: ld)
            lh.setPersist(true); lh.add(.text("saved")); lh.flush()
            lk.failing = true
            let locked = history("l", keys: lk, d: ld)
            locked.start(); locked.stop()
            lk.failing = false
            let next = history("l", keys: lk, d: ld)
            next.start(); next.stop()
            check("persistence: a Keychain refusal at launch keeps the choice; the next launch saves again",
                  !locked.saving && locked.problem != nil && ClipSettings.load(ld).persist && next.saving && next.items.map(\.text) == ["saved"])
        }

        let wk = MemoryKeyStore(), wb = FakePasteboard()
        let wh = history("w", keys: wk, board: wb)
        wh.setPersist(true)
        wb.put(text("one")); wh.captureNow()
        wb.put(ClipSnapshot(types: ["public.png"], image: png, width: 4, height: 3)); wh.captureNow()
        wh.togglePin(wh.items[0].id)
        wh.flush()
        let oldKey = wk.key
        let wiped = wh.deleteEverything()
        wh.flush()
        let wdir = root.appendingPathComponent("w")
        let leftovers = ((try? fm.contentsOfDirectory(atPath: wdir.path)) ?? []).filter { $0 != "index.ccl" }
        check("delete everything: items, favorites, files and key are gone", wiped && wh.items.isEmpty && leftovers.isEmpty && wk.key != oldKey)
        let afterWipe = history("w", keys: wk, board: FakePasteboard())
        afterWipe.setPersist(true)
        check("delete everything: nothing comes back after a restart", afterWipe.items.isEmpty)
        afterWipe.setPersist(false, wipe: true)
        let lh = history("leftover", keys: MemoryKeyStore())
        lh.setPersist(true); lh.add(.text("x")); lh.flush(); lh.setPersist(false, wipe: false)
        lh.deleteEverything()
        check("delete everything: also removes files kept from an earlier time", !fm.fileExists(atPath: root.appendingPathComponent("leftover").path))

        var oldSettings = Data("{\"maxItems\":200}".utf8)
        let sd = defaults(); sd.set(oldSettings, forKey: ClipSettings.key)
        check("settings: missing keys take defaults", ClipSettings.load(sd).maxItems == 200 && !ClipSettings.load(sd).persist && ClipSettings.load(sd).skipSecrets)
        oldSettings = Data("garbage".utf8); sd.set(oldSettings, forKey: ClipSettings.key)
        check("settings: damaged settings fall back to defaults", ClipSettings.load(sd) == ClipSettings())

        failed += realPasteboard()
        failed += realKeychain(root)
        return failed
    }

    /// A 4×3 PNG.
    static func samplePNG() -> Data {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 3, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                   isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        rep.setColor(NSColor(deviceRed: 1, green: 0.4, blue: 0.7, alpha: 1), atX: 1, y: 1)
        return rep.representation(using: .png, properties: [:])!
    }

    /// The real NSPasteboard code, on a uniquely named pasteboard (never the general one).
    private static func realPasteboard() -> Int {
        var failed = 0
        func check(_ name: String, _ ok: Bool) { print((ok ? "PASS" : "FAIL") + "  clipboard: " + name); if !ok { failed += 1 } }
        let pb = NSPasteboard(name: NSPasteboard.Name("local.cocaine.cliptest.\(getpid()).\(UUID().uuidString)"))
        defer { pb.releaseGlobally() }
        let board = SystemPasteboard(pb)
        let all: ([String], String?) -> Bool = { _, _ in true }
        pb.clearContents(); pb.setString("plain words", forType: .string)
        check("pasteboard: plain text is read", board.snapshot(maxImageBytes: 1_000_000, allowed: all).text == "plain words")
        pb.clearContents()
        let rtf = NSAttributedString(string: "bold words", attributes: [.font: NSFont.boldSystemFont(ofSize: 12)])
        pb.setData(try? rtf.data(from: NSRange(location: 0, length: rtf.length), documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf]), forType: .rtf)
        check("pasteboard: rich text keeps its plain text", board.snapshot(maxImageBytes: 1_000_000, allowed: all).text == "bold words")
        pb.clearContents()
        pb.setString("hunter2", forType: .string); pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        let concealed = board.snapshot(maxImageBytes: 1_000_000) { types, _ in !ClipRules.isConcealed(types) }
        check("pasteboard: concealed content isn't read", concealed.text == nil && ClipRules.isConcealed(concealed.types))
        pb.clearContents()
        pb.setString("x", forType: .string); pb.setString("com.example.app", forType: NSPasteboard.PasteboardType("org.nspasteboard.source"))
        check("pasteboard: the source app marker is read", board.snapshot(maxImageBytes: 1_000_000, allowed: all).source == "com.example.app")
        let png = samplePNG()
        pb.clearContents(); pb.setData(png, forType: .png)
        let im = board.snapshot(maxImageBytes: 1_000_000, allowed: all)
        check("pasteboard: a PNG is read with its size", im.image == png && im.width == 4 && im.height == 3)
        pb.clearContents(); pb.setData(NSBitmapImageRep(data: png)!.tiffRepresentation!, forType: .tiff)
        let tf = board.snapshot(maxImageBytes: 1_000_000, allowed: all)
        check("pasteboard: a TIFF becomes a PNG", tf.image.map { NSBitmapImageRep(data: $0) != nil && $0.starts(with: [0x89, 0x50, 0x4E, 0x47]) } == true && tf.width == 4)
        check("pasteboard: an image over the limit isn't kept", board.snapshot(maxImageBytes: 10, allowed: all).imageTooBig)
        let file = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("cocaine-clip-\(getpid()).txt")
        try? Data("x".utf8).write(to: file)
        defer { try? FileManager.default.removeItem(at: file) }
        pb.clearContents(); pb.writeObjects([file as NSURL])
        check("pasteboard: copied files are read as references", board.snapshot(maxImageBytes: 1_000_000, allowed: all).files.map(\.path) == [file.path])
        // Writing back: the right types, and marked as ours.
        let before = pb.changeCount
        let c1 = board.write(.text("again"), payload: nil)
        let back = board.snapshot(maxImageBytes: 1_000_000, allowed: all)
        check("pasteboard: text written back is plain text, marked as ours", c1 != nil && c1 != before && pb.string(forType: .string) == "again" && back.ours)
        _ = board.write(.image(png: png, width: 4, height: 3), payload: png)
        check("pasteboard: an image is written back as PNG and TIFF", pb.data(forType: .png) == png && pb.data(forType: .tiff) != nil
              && NSImage(pasteboard: pb) != nil)
        _ = board.write(.files([file.path]), payload: nil)
        let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        check("pasteboard: files are written back as file URLs", urls?.map(\.path) == [file.path] && pb.types?.contains(NSPasteboard.PasteboardType(ClipRules.ownType)) == true)
        check("pasteboard: a missing file isn't written", board.write(.files(["/nonexistent/cocaine-\(UUID().uuidString)"]), payload: nil) == nil)
        return failed
    }

    /// The Keychain code against a temporary keychain file (not the login keychain), made and deleted here.
    private static func realKeychain(_ root: URL) -> Int {
        var failed = 0
        func check(_ name: String, _ ok: Bool) { print((ok ? "PASS" : "FAIL") + "  clipboard: " + name); if !ok { failed += 1 } }
        let path = root.appendingPathComponent("test.keychain-db").path
        func security(_ args: [String]) -> Int32 {
            let p = Process()
            p.executableURL = URL(fileURLWithPath: "/usr/bin/security")
            p.arguments = args
            p.standardOutput = FileHandle.nullDevice; p.standardError = FileHandle.nullDevice
            do { try p.run() } catch { return -1 }
            p.waitUntilExit()
            return p.terminationStatus
        }
        guard security(["create-keychain", "-p", "cocaine-test", path]) == 0 else {
            print("SKIP  clipboard: keychain (can't make a temporary keychain here)")
            return 0
        }
        defer { _ = security(["delete-keychain", path]) }
        _ = security(["unlock-keychain", "-p", "cocaine-test", path])
        var kc: SecKeychain?
        guard SecKeychainOpen(path, &kc) == errSecSuccess, let kc else { check("keychain: temporary keychain opens", false); return failed }
        let store = KeychainKeyStore(service: "local.cocaine.clipboard.test", account: "k", keychain: kc)
        check("keychain: nothing there at first", (try? store.load()) == .some(nil))
        let key = Data((0..<32).map { _ in UInt8.random(in: 0...255) })
        check("keychain: a key is saved and read back", (try? store.save(key)) != nil && (try? store.load()) == .some(key))
        let other = Data((0..<32).map { _ in UInt8.random(in: 0...255) })
        check("keychain: saving again replaces it", (try? store.save(other)) != nil && (try? store.load()) == .some(other))
        let cs = ClipStore(dir: root.appendingPathComponent("kc"), keys: store)
        check("keychain: the store uses it", (try? cs.unlock()) != nil && (try? cs.saveIndex([.text("k")])) != nil)
        check("keychain: delete removes it (and deleting again is fine)", (try? store.delete()) != nil && (try? store.load()) == .some(nil) && (try? store.delete()) != nil)
        check("keychain: the login keychain was not used", (try? KeychainKeyStore(service: "local.cocaine.clipboard.test", account: "k").load()) == .some(nil))
        return failed
    }
